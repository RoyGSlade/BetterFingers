"""Signed approvals: proof that a person tapped, minted only by the Electron main process.

THE PROBLEM THIS CLOSES (Phase 0 item 1). "The human tap decides" was a rule the
code never enforced. Approving a workflow, adding a persona example with
``consent=true``, sending a draft and confirming a voice command were all values
the CALLER put in a request body, so any holder of the bearer token (a compromised
renderer, an MCP server that inherited the token, a future tool-calling model)
could approve its own proposal and the owner would never see a preview.

THE CONTRACT. The owner's yes is a native dialog shown by the Electron MAIN
process (``app/src/main/approvalBroker.js``) that displays the exact, complete
thing being approved. Only if the person clicks the approving button does main
sign a *ticket* with an HMAC key that

* is generated by main for this run and handed only to this backend process
  (environment variable, removed from ``os.environ`` the moment it is read, and
  scrubbed from every child process this backend launches),
* is never sent to a renderer, never returned by any route, never logged.

A renderer can ask main to show a dialog; it cannot make main say yes. A token
holder can call every backend route; it still cannot produce a ticket, because it
does not have the key. This module is the verifying half.

A TICKET is ``{"payload": <base64url JSON>, "sig": <hex HMAC-SHA256 of the payload
string>}``. The payload names its ``purpose`` (what kind of approval), its
``subject`` (which workflow / persona / draft) and a ``bind`` map of digests of
the exact content shown in the dialog. ``verify`` accepts a ticket only if the
signature is valid, it has not expired (short lifetime), its nonce has never been
seen, and purpose, subject and EVERY bound digest equal what this backend computes
from its own current state. Changing the workflow, the draft text or the persona
example after the dialog therefore voids the approval, and a ticket cannot be
replayed for a second action.

No key configured means no approval: ``verify`` fails closed (a backend started
outside the Electron shell cannot approve anything until it is given a key).
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import json
import os
import threading
import time
from dataclasses import dataclass
from typing import Mapping, Optional, Sequence

TICKET_VERSION = 1
#: A ticket is minted right after the click and spent immediately; anything older
#: than this is refused whatever its signature says.
MAX_TICKET_LIFETIME_S = 120
_CLOCK_SKEW_S = 30
_MAX_PAYLOAD_CHARS = 4096
_MIN_KEY_BYTES = 32

PURPOSE_WORKFLOW_APPROVE = "workflow.approve"
PURPOSE_PERSONA_EXAMPLE = "persona.example"
PURPOSE_DRAFT_SEND = "draft.send"
PURPOSE_VOICE_CONFIRM = "voice.confirm"
PURPOSES = frozenset({
    PURPOSE_WORKFLOW_APPROVE, PURPOSE_PERSONA_EXAMPLE, PURPOSE_DRAFT_SEND, PURPOSE_VOICE_CONFIRM,
})

# Error codes. The messages are deliberately generic: they say what is missing,
# never which part of a forged ticket was wrong.
ERR_UNAVAILABLE = "approval_unavailable"
ERR_REQUIRED = "approval_required"
ERR_INVALID = "approval_invalid"

_MESSAGES = {
    ERR_UNAVAILABLE: "Approvals are not available: this backend was not started by the BetterFingers app.",
    ERR_REQUIRED: "This needs your approval in the BetterFingers window. Nothing was done.",
    ERR_INVALID: "That approval is not valid (expired, already used, or for something else). Nothing was done.",
}

#: Production default. Tests relax it per file (tests/conftest.py); nothing else
#: may. ``verify`` still returns the same ``VerifiedApproval`` type either way.
ENFORCE = True

_lock = threading.Lock()
_secret: Optional[bytes] = None
_spent: dict = {}  # nonce -> expiry (epoch seconds); bounded by pruning on use
_SEAL = object()


class ApprovalError(Exception):
    """Raised by :func:`verify`; ``code`` is one of the ``ERR_*`` constants."""

    def __init__(self, code: str):
        super().__init__(_MESSAGES.get(code, code))
        self.code = code
        self.message = _MESSAGES.get(code, code)


@dataclass(frozen=True)
class VerifiedApproval:
    """What a successful :func:`verify` returns. Stores that mutate on approval
    require one, so an in-process caller cannot reach them without a ticket that
    passed verification."""

    purpose: str
    subject: str
    bind: Mapping[str, str]
    nonce: str
    _seal: object = None

    def is_genuine(self) -> bool:
        return self._seal is _SEAL


# --- configuration -----------------------------------------------------------

def configure(secret) -> None:
    """Install the verification key (bytes, or a hex string of at least 32 bytes)."""
    global _secret
    key = _coerce_key(secret)
    with _lock:
        _secret = key
        _spent.clear()


def configure_from_env(env=None, name: str = "BETTERFINGERS_APPROVAL_KEY") -> bool:
    """Take the key from the environment and REMOVE it from there.

    Removal matters as much as reading: ``os.environ`` is inherited by every
    process this backend spawns (MCP servers, llama-server), and the key must not
    ride along. Returns True when a usable key was installed.
    """
    environ = os.environ if env is None else env
    raw = environ.pop(name, None)
    if not raw:
        return False
    try:
        configure(raw)
    except ValueError:
        return False
    return True


def reset() -> None:
    """Forget the key and every spent nonce (tests; a backend restart)."""
    global _secret
    with _lock:
        _secret = None
        _spent.clear()


def is_configured() -> bool:
    return _secret is not None


def _coerce_key(secret) -> bytes:
    if isinstance(secret, str):
        text = secret.strip()
        try:
            key = binascii.unhexlify(text)
        except (binascii.Error, ValueError):
            key = text.encode("utf-8")
    elif isinstance(secret, (bytes, bytearray)):
        key = bytes(secret)
    else:
        raise ValueError("approval key must be bytes or a string")
    if len(key) < _MIN_KEY_BYTES:
        raise ValueError("approval key is too short")
    return key


# --- digests (mirrored byte for byte in app/src/main/approvalBroker.js) -------

def lines_digest(lines: Sequence[str]) -> str:
    """SHA-256 over length-framed UTF-8 lines.

    Each line contributes ``<byte length>:<bytes>\\n``, so ``["ab", "c"]`` and
    ``["a", "bc"]`` hash differently and no line can be merged into its
    neighbour. The digest covers the COMPLETE text: there is no truncation
    anywhere on this path (Phase 0 item 2). The Node implementation produces the
    same bytes; ``tests/test_approvals.py`` and ``app/tests/approvalBroker.test.mjs``
    share a fixed test vector.
    """
    digest = hashlib.sha256()
    for line in lines:
        data = str(line).encode("utf-8")
        digest.update(f"{len(data)}:".encode("ascii"))
        digest.update(data)
        digest.update(b"\n")
    return digest.hexdigest()


def preview_digest(lines: Sequence[str]) -> str:
    return lines_digest(lines)


def steps_digest(steps) -> str:
    """Digest of a workflow's step list in canonical JSON (sorted keys, ASCII)."""
    canonical = json.dumps(steps, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(canonical.encode("ascii")).hexdigest()


def text_digest(text: str) -> str:
    return lines_digest([str(text)])


# --- what each kind of approval binds to --------------------------------------
# The bind map is what the person saw in the dialog, as digests. The Node broker
# builds the same maps (approvalBroker.js); routes build them from their OWN
# current state and hand them to ``verify``, which demands equality.

def workflow_bind(preview_lines: Sequence[str], steps) -> dict:
    return {"preview_sha256": preview_digest(preview_lines), "steps_sha256": steps_digest(steps)}


def persona_example_bind(persona: str, raw: str, out: str) -> dict:
    return {"example_sha256": lines_digest([str(persona), str(raw), str(out)])}


def draft_send_bind(action: str, text: str, open_chat: bool = False) -> dict:
    return {"action": str(action), "text_sha256": text_digest(text), "open_chat": "1" if open_chat else "0"}


def voice_confirm_bind(action: str, draft_id, text: str = "") -> dict:
    return {
        "action": str(action),
        "draft_id": "" if draft_id is None else str(draft_id),
        "text_sha256": text_digest(text),
    }


# --- verification --------------------------------------------------------------

def _b64url_decode(text: str) -> bytes:
    padded = text + "=" * (-len(text) % 4)
    return base64.urlsafe_b64decode(padded.encode("ascii"))


def verify(
    ticket,
    *,
    purpose: str,
    subject: str,
    bind: Mapping[str, str],
    now: Optional[float] = None,
) -> VerifiedApproval:
    """Accept ``ticket`` only for exactly this purpose, subject and content.

    Raises :class:`ApprovalError` otherwise. A ticket is single-use: a successful
    verification spends its nonce.
    """
    if purpose not in PURPOSES:
        raise ApprovalError(ERR_INVALID)

    if not ENFORCE:
        # Test-suite relaxation only (see tests/conftest.py); never reachable in a
        # packaged app, where ENFORCE keeps its default.
        return VerifiedApproval(purpose, str(subject), dict(bind), "relaxed", _SEAL)

    if _secret is None:
        raise ApprovalError(ERR_UNAVAILABLE)
    if ticket is None:
        raise ApprovalError(ERR_REQUIRED)
    if not isinstance(ticket, Mapping):
        raise ApprovalError(ERR_INVALID)
    payload_b64 = ticket.get("payload")
    signature = ticket.get("sig")
    if not isinstance(payload_b64, str) or not isinstance(signature, str):
        raise ApprovalError(ERR_INVALID)
    if not payload_b64 or len(payload_b64) > _MAX_PAYLOAD_CHARS or len(signature) != 64:
        raise ApprovalError(ERR_INVALID)

    expected = hmac.new(_secret, payload_b64.encode("ascii", "replace"), hashlib.sha256).hexdigest()
    if not hmac.compare_digest(expected, signature.lower()):
        raise ApprovalError(ERR_INVALID)

    try:
        payload = json.loads(_b64url_decode(payload_b64).decode("utf-8"))
    except (ValueError, binascii.Error, UnicodeError):
        raise ApprovalError(ERR_INVALID) from None
    if not isinstance(payload, dict) or payload.get("v") != TICKET_VERSION:
        raise ApprovalError(ERR_INVALID)

    if payload.get("purpose") != purpose or payload.get("subject") != str(subject):
        raise ApprovalError(ERR_INVALID)
    ticket_bind = payload.get("bind")
    if not isinstance(ticket_bind, dict) or ticket_bind != {str(k): str(v) for k, v in bind.items()}:
        raise ApprovalError(ERR_INVALID)

    nonce = payload.get("nonce")
    issued, expires = payload.get("iat"), payload.get("exp")
    if not isinstance(nonce, str) or not (16 <= len(nonce) <= 128):
        raise ApprovalError(ERR_INVALID)
    if isinstance(issued, bool) or isinstance(expires, bool) or not all(
        isinstance(v, (int, float)) for v in (issued, expires)
    ):
        raise ApprovalError(ERR_INVALID)
    moment = time.time() if now is None else now
    if expires < moment or expires - issued > MAX_TICKET_LIFETIME_S or issued > moment + _CLOCK_SKEW_S:
        raise ApprovalError(ERR_INVALID)

    with _lock:
        for spent_nonce in [n for n, exp in _spent.items() if exp < moment]:
            del _spent[spent_nonce]
        if nonce in _spent:
            raise ApprovalError(ERR_INVALID)
        _spent[nonce] = float(expires)

    return VerifiedApproval(purpose, str(subject), dict(ticket_bind), nonce, _SEAL)


def require_verified(proof, *, purpose: str, subject: Optional[str] = None) -> bool:
    """True when ``proof`` came out of :func:`verify` for this purpose (and subject)."""
    return (
        isinstance(proof, VerifiedApproval)
        and proof.is_genuine()
        and proof.purpose == purpose
        and (subject is None or proof.subject == str(subject))
    )


def http_status_for(code: str) -> int:
    """403 for a missing/invalid ticket, 503 when no key exists at all."""
    return 503 if code == ERR_UNAVAILABLE else 403
